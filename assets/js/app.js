// Project Mímir: a tiny no-build site that renders curriculum/curriculum.json
// and the Markdown lesson files under curriculum/.
(function () {
  "use strict";

  const main = document.getElementById("main");
  const HOME_HTML = main.innerHTML;
  const HOME_TITLE = document.title;
  const PROGRESS_KEY = "mimir:completed";
  let manifest = null;

  // ---------- progress (browser-only) ----------
  function loadProgress() {
    try { return new Set(JSON.parse(localStorage.getItem(PROGRESS_KEY) || "[]")); }
    catch (e) { return new Set(); }
  }
  let completed = loadProgress();
  function saveProgress() {
    try { localStorage.setItem(PROGRESS_KEY, JSON.stringify([...completed])); } catch (e) { /* storage unavailable */ }
  }
  const key = (path, lesson) => `${path.id}/${lesson.id}`;

  // ---------- helpers ----------
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const allLessons = (path) => path.sections.flatMap((s) => s.lessons.map((l) => ({ ...l, section: s })));
  const pct = (d, t) => (t ? Math.round((d / t) * 100) : 0);
  function counts(path) {
    const lessons = allLessons(path);
    return { total: lessons.length, done: lessons.filter((l) => completed.has(key(path, l))).length, projects: lessons.filter((l) => l.project).length };
  }
  const findPath = (id) => manifest.paths.find((p) => p.id === id);
  const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

  function setTitle(t) { document.title = t ? `${t} | Project Mímir` : HOME_TITLE; }
  function setNav(name) {
    document.querySelectorAll("[data-nav]").forEach((a) => {
      if (a.dataset.nav === name) a.setAttribute("aria-current", "page"); else a.removeAttribute("aria-current");
    });
  }
  function showError(msg) {
    main.innerHTML = `<div class="error"><strong>Something went wrong.</strong> ${esc(msg)}</div>`;
  }

  // ---------- views ----------
  // The home page is static HTML (generated by scripts/build.py so search engines can read it).
  // Keep a copy and restore it, then fill in this browser's progress.
  function viewHome() {
    setTitle(""); setNav("home");
    main.innerHTML = HOME_HTML;
    main.querySelectorAll("[data-path]").forEach((card) => {
      const path = findPath(card.dataset.path);
      if (!path) return;
      const c = counts(path);
      const bar = card.querySelector(".progress");
      bar.setAttribute("aria-label", `${pct(c.done, c.total)}% complete`);
      bar.firstElementChild.style.width = `${pct(c.done, c.total)}%`;
    });
  }

  function viewPath(pathId) {
    const path = findPath(pathId);
    if (!path) return showError("That path doesn't exist.");
    setTitle(path.title); setNav("home");
    const c = counts(path);
    main.innerHTML = `
      <nav class="crumbs" aria-label="Breadcrumb"><a href="#/">Paths</a><span>/</span><span>${esc(path.title)}</span></nav>
      <header class="path-head">
        <div class="eyebrow">Path ${String(manifest.paths.indexOf(path)).padStart(2, "0")}${path.optional ? " · Elective" : ""}</div>
        <h1>${esc(path.title)}</h1>
        <p class="lead">${esc(path.description)}</p>
        ${(path.requires || []).length ? `<p class="requires">Requires: ${path.requires.map((id) => { const r = findPath(id); return r ? `<a href="#/paths/${r.id}">${esc(r.title)}</a>` : ""; }).join(", ")}</p>` : ""}
        <div class="path-stats"><span>~${path.hours} hours</span><span>${path.sections.length} sections</span><span>${c.total} lessons</span><span>${c.projects} projects</span><span>${c.done}/${c.total} complete</span></div>
        <div class="progress"><i style="width:${pct(c.done, c.total)}%"></i></div>
      </header>
      ${path.sections.map((s) => `
        <section class="course-section">
          <h2>${esc(s.title)}</h2>
          <p>${esc(s.description)}</p>
          <ol class="lesson-list">
            ${s.lessons.map((l) => {
              const isDone = completed.has(key(path, l));
              return `<li><a class="lesson-row" href="#/lessons/${path.id}/${l.id}">
                <span class="dot${isDone ? " done" : ""}" aria-label="${isDone ? "Completed" : "Not completed"}"></span>
                <span><span class="title">${esc(l.title)}</span><span class="desc">${esc(l.description)}</span></span>
                ${l.project ? '<span class="tag project">Project</span>' : "<span></span>"}
              </a></li>`;
            }).join("")}
          </ol>
        </section>`).join("")}`;
  }

  async function viewLesson(pathId, lessonId) {
    const path = findPath(pathId);
    const lessons = path ? allLessons(path) : [];
    const idx = lessons.findIndex((l) => l.id === lessonId);
    if (idx === -1) return showError("That lesson doesn't exist.");
    const lesson = lessons[idx];
    setTitle(lesson.title); setNav("home");
    main.innerHTML = `<p class="loading">Loading lesson…</p>`;

    let md;
    try {
      const res = await fetch(`curriculum/${lesson.file}`);
      if (!res.ok) throw new Error(res.status);
      md = await res.text();
    } catch (e) {
      return showError(`Couldn't load ${lesson.file}. If you opened index.html directly from your disk, run a local server instead (see the README).`);
    }

    const html = DOMPurify.sanitize(marked.parse(md), { ADD_ATTR: ["target"] });
    const prev = lessons[idx - 1], next = lessons[idx + 1];
    const isDone = completed.has(key(path, lesson));

    main.innerHTML = `
      <nav class="crumbs" aria-label="Breadcrumb"><a href="#/">Paths</a><span>/</span><a href="#/paths/${path.id}">${esc(path.title)}</a><span>/</span><span>${esc(lesson.section.title)}</span></nav>
      <div class="lesson-layout">
        <article>
          <header class="lesson-head">
            <div class="eyebrow">${lesson.project ? "Project" : "Lesson"} · ${esc(lesson.section.title)}</div>
            <h1>${esc(lesson.title)}</h1>
          </header>
          <div class="prose" id="lessonBody">${html}</div>
          <div class="lesson-foot">
            <button class="btn${isDone ? " done" : ""}" id="completeBtn" type="button" aria-pressed="${isDone}">${isDone ? "Completed ✓" : "Mark as complete"}</button>
            <div class="pager">
              ${prev ? `<a class="btn secondary" href="#/lessons/${path.id}/${prev.id}">← ${esc(prev.title)}</a>` : ""}
              ${next ? `<a class="btn secondary" href="#/lessons/${path.id}/${next.id}">${esc(next.title)} →</a>` : `<a class="btn secondary" href="#/paths/${path.id}">Back to ${esc(path.title)}</a>`}
            </div>
          </div>
        </article>
        <aside class="toc" id="toc" aria-label="On this page"></aside>
      </div>`;

    const body = document.getElementById("lessonBody");
    body.querySelectorAll("a[href^='http']").forEach((a) => { a.target = "_blank"; a.rel = "noopener"; });
    body.querySelectorAll("pre code").forEach((el) => { if (window.hljs) hljs.highlightElement(el); });

    const heads = [...body.querySelectorAll("h3")];
    heads.forEach((h) => { h.id = slug(h.textContent); });
    // In-lesson anchors such as knowledge-check links ("#chunking") must go through the router.
    body.querySelectorAll("a[href^='#']:not([href^='#/'])").forEach((a) => {
      a.setAttribute("href", `#/lessons/${path.id}/${lesson.id}/${a.getAttribute("href").slice(1)}`);
    });
    if (heads.length > 1) {
      document.getElementById("toc").innerHTML = `<div class="eyebrow">On this page</div><ol>${heads.map((h) => `<li><a href="#/lessons/${path.id}/${lesson.id}/${h.id}" data-anchor="${h.id}">${esc(h.textContent)}</a></li>`).join("")}</ol>`;
    }

    document.getElementById("completeBtn").addEventListener("click", (e) => {
      const k = key(path, lesson);
      if (completed.has(k)) completed.delete(k); else completed.add(k);
      saveProgress();
      const done = completed.has(k);
      e.currentTarget.classList.toggle("done", done);
      e.currentTarget.setAttribute("aria-pressed", done);
      e.currentTarget.textContent = done ? "Completed ✓" : "Mark as complete";
    });
  }

  // Standalone Markdown pages outside the paths (curriculum/<name>.md).
  const PAGES = { about: "About", models: "Current Models" };
  async function viewPage(name) {
    setTitle(PAGES[name]); setNav(name);
    try {
      const res = await fetch(`curriculum/${name}.md`);
      if (!res.ok) throw new Error(res.status);
      const md = await res.text();
      main.innerHTML = `<article class="about"><div class="prose">${DOMPurify.sanitize(marked.parse(md))}</div></article>`;
      main.querySelectorAll(".prose a[href^='http']").forEach((a) => { a.target = "_blank"; a.rel = "noopener"; });
    } catch (e) { showError(`Couldn't load the ${PAGES[name]} page.`); }
  }

  // ---------- router ----------
  // Routes: #/  ·  #/about  ·  #/models  ·  #/paths/:path  ·  #/lessons/:path/:lesson[/:anchor]
  async function route() {
    const parts = location.hash.replace(/^#\/?/, "").split("/").filter(Boolean);
    if (parts[0] === "paths" && parts[1]) viewPath(parts[1]);
    else if (parts[0] === "lessons" && parts[2]) {
      const sameLesson = main.dataset.lesson === `${parts[1]}/${parts[2]}`;
      if (!sameLesson) { await viewLesson(parts[1], parts[2]); main.dataset.lesson = `${parts[1]}/${parts[2]}`; }
      if (parts[3]) { document.getElementById(parts[3])?.scrollIntoView(); return; }
    }
    else if (PAGES[parts[0]]) viewPage(parts[0]);
    else viewHome();
    if (parts[0] !== "lessons") delete main.dataset.lesson;
    window.scrollTo(0, 0);
  }

  marked.use({ gfm: true });
  fetch("curriculum/curriculum.json")
    .then((r) => { if (!r.ok) throw new Error(r.status); return r.json(); })
    .then((data) => { manifest = data; window.addEventListener("hashchange", route); route(); })
    .catch(() => showError("Couldn't load curriculum/curriculum.json. If you opened index.html directly from your disk, run a local server instead (see the README)."));
})();
